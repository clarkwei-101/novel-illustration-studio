/**
 * Domain model for the novel illustration workflow.
 *
 * Design constraint: the server performs NO language-model inference.
 * Everything below is either (a) deterministic extraction from the source
 * text, or (b) content authored by an external AI agent and posted back.
 * The agent (Cursor / Claude / any MCP client) is the brain; this service is
 * the workshop bench.
 */

/** A parsed chapter of the uploaded novel. */
export interface Chapter {
  index: number;
  title: string;
  /** Character offsets into the normalized full text. */
  start: number;
  end: number;
  /** Rough word/character count, used for weighting and budgeting. */
  length: number;
  /** First ~300 chars, handy as an LLM-free preview. */
  preview: string;
}

export type Category =
  | "character"
  | "scene"
  | "object"
  | "event"
  | "emotion"
  | "theme";

/**
 * How a keyword can be used in a prompt.
 *
 * The buckets are chosen by what an illustrator does with the word, not
 * by grammar: an `object` goes in the frame, a `place` sets the
 * location, a `nature` word sets the light and palette, and a `concept`
 * implies a whole gathering or event that has to be composed.
 */
export type KeywordCategory = "object" | "place" | "nature" | "concept";

/** A sub-classification slot inside a category. */
export interface Subcategory {
  key: string;
  label: string;
}

/**
 * Taxonomy. Each category can be refined into subcategories. The taxonomy is
 * intentionally data-driven so an agent can propose a refined taxonomy for a
 * specific work without a code change (see POST /api/taxonomy).
 */
export interface Taxonomy {
  id: string;
  version: number;
  /** Built-in seed taxonomy, always present. */
  builtin: Record<Category, Subcategory[]>;
  /** Extra categories contributed by an agent for a specific novel. */
  extra?: Record<string, Subcategory[]>;
}

/** A detected entity extracted from the text. */
export interface Entity {
  id: string;
  name: string;
  category: Category;
  /** Subcategory key; must exist in the taxonomy. */
  subcategory: string;
  /** Number of times the surface form occurs. */
  mentions: number;
  /** Fraction of chapters in which the entity appears (0..1). */
  chapterSpread: number;
  /** Direct quotations surrounding the entity — evidence for an agent to judge. */
  evidence: string[];
  /** Short deterministic descriptor assembled from co-occurring sentences. */
  summary: string;
  /** Free-form attributes an agent may attach (age, appearance, role...). */
  attributes: Record<string, string>;
  /** Set when an agent confirms/revises the entity. */
  agentReviewed?: boolean;
  agentNote?: string;
}

/** A directed relationship between two entities. */
export interface Relationship {
  id: string;
  sourceId: string;
  targetId: string;
  /** Deterministic evidence-based strength (number of co-occurrences). */
  weight: number;
  /** "A 出现在 B 的对话中" etc. */
  kinds: string[];
  evidence: string[];
  agentLabel?: string;
  agentReviewed?: boolean;
}

/** A scene: a place/event unit the story happens in. */
export interface Scene {
  id: string;
  title: string;
  subcategory: string;
  /** Chapter indices where this scene is referenced. */
  chapters: number[];
  mentions: number;
  summary: string;
  attributes: Record<string, string>;
  agentReviewed?: boolean;
}

export type RelationKind =
  | "co-occurrence"
  | "dialogue"
  | "addressed-to"
  | "action-target";

/** The whole deterministic analysis of one novel. */
export interface Analysis {
  novelId: string;
  generatedAt: string;
  stats: {
    characters: number;
    scenes: number;
    relationships: number;
    chapters: number;
    totalChars: number;
  };
  entities: Entity[];
  scenes: Scene[];
  relationships: Relationship[];
  /** Terms that recur but are not entities — themes / motifs. */
  keywords: { term: string; count: number; category: KeywordCategory }[];
}

/** One story beat / shot — the unit a prompt is generated for. */
export interface Shot {
  id: string;
  novelId: string;
  index: number;
  title: string;
  /** Chapter the shot comes from. */
  chapterIndex: number;
  /** Quoted source passage the shot is based on. */
  excerpt: string;
  /** Entities involved, by id. */
  entityIds: string[];
  sceneId?: string;
  /** Emotion / tone tag. */
  mood?: string;
  /** Visual style for the whole story, e.g. "电影级质感, 胶片颗粒". */
  style?: string;
  /** Target duration in seconds for Seedance (4..15). */
  durationSec?: number;
  /** Agent-authored notes. */
  notes?: string;
  /** Reference assets the agent intends to upload to Seedance. */
  references?: SeedanceReference[];
  /** Prompt text, generated by the assembler. */
  prompt?: string;
  /** Result of validating `prompt`. */
  validation?: PromptValidation;
  agentReviewed?: boolean;
}

/** A material the user will attach to a Seedance 2.0 generation. */
export interface SeedanceReference {
  /** Slot name used in the prompt, e.g. "图片1", "视频1", "音频1". */
  slot: string;
  kind: "image" | "video" | "audio";
  /** What the reference is used for — REQUIRED by the skill for every slot. */
  purpose: string;
  note?: string;
}

/** Result of running the Seedance constraint checker over a prompt. */
export interface PromptValidation {
  ok: boolean;
  /** Hard violations: rendering will be rejected or produce garbage. */
  errors: string[];
  /** Soft warnings: allowed, but likely to reduce quality. */
  warnings: string[];
  /** Derived facts extracted from the prompt. */
  facts: {
    durationSec: number | null;
    imageRefs: string[];
    videoRefs: string[];
    audioRefs: string[];
    hasTimeline: boolean;
    hasCamera: boolean;
    hasAudioDesign: boolean;
    hasStyle: boolean;
    hasRealFace: boolean;
    wordCount: number;
  };
}

/** A stored novel. */
export interface Novel {
  id: string;
  title: string;
  /** Original filename. */
  filename: string;
  /** Detected source format. */
  format: "txt" | "pdf" | "docx" | "epub" | "md";
  bytes: number;
  chars: number;
  chapters: number;
  createdAt: string;
  updatedAt: string;
  /** Whether an agent has posted refined entities back. */
  analysisVersion: number;
  /** Short blurb used for cards. */
  synopsis: string;
  language: "zh" | "en" | "mixed" | "unknown";
}

/** Seedance prompt templates distilled from the seedance-prompt-zh skill. */
export interface PromptTemplate {
  id: string;
  title: string;
  /** Which skill scenario this mirrors. */
  scenario: string;
  description: string;
  durationSec: number;
  /** Placeholder skeleton, e.g. {主体} {场景} {动作}. */
  skeleton: string;
  /** Whether a segmented timeline is required. */
  segmented: boolean;
  /** Asset slots the template expects. */
  slots: { slot: string; kind: "image" | "video" | "audio"; purpose: string }[];
}
